    loadSettings() {
        const saved = localStorage.getItem('pirate_team_settings');
        if (saved) {
            const s = JSON.parse(saved);
            this.lang = s.lang || this.getDeviceLanguage();
        } else {
            this.lang = this.getDeviceLanguage();
        }
    }

    getDeviceLanguage() {
        const userLang = navigator.language || navigator.userLanguage;
        if (userLang.startsWith('ru')) return 'ru';
        if (userLang.startsWith('tr')) return 'tr';
        if (userLang.startsWith('ar')) return 'ar';
        return 'en';
    }

    async initialize() {
        const progressBar = document.getElementById('loader-progress-bar');
        const loaderPercent = document.getElementById('loader-percent');
        const loaderTips = document.querySelectorAll('.loader-tip');
        let tipIndex = 0;
        
        const updateProgress = (percent) => {
            if (progressBar) progressBar.style.width = percent + '%';
            if (loaderPercent) loaderPercent.innerText = Math.floor(percent) + '%';
        };
        
        const rotateTips = () => {
            loaderTips.forEach((tip, i) => {
                tip.classList.toggle('active', i === tipIndex);
            });
            tipIndex = (tipIndex + 1) % loaderTips.length;
        };
        
        const tipInterval = setInterval(rotateTips, 3000);
        
        try {
            updateProgress(5);
            
            if (!window.Telegram?.WebApp) {
                throw new Error('Open from Telegram');
            }
            
            this.tg = window.Telegram.WebApp;
            this.tgUser = this.tg.initDataUnsafe.user;
            
            if (!this.tgUser) {
                throw new Error('No user data');
            }
            
            this.tg.ready();
            this.tg.expand();
            updateProgress(15);
            
            await this.getConfig();
            updateProgress(30);
            
            await this.getServerTime();
            updateProgress(45);
            
            const startParam = this.tg.initDataUnsafe?.start_param;
            if (startParam && !isNaN(startParam) && parseInt(startParam) !== this.tgUser.id) {
                this.referredBy = parseInt(startParam);
            }
            
            await this.loadUserData();
            updateProgress(70);
            
            const headerHtml = `
                <div class="header-balances" id="header-balances">
                    <div class="header-balance" id="header-power"><i class="fas fa-bolt"></i> ${this.formatNumber(Math.floor(this.powerBalance))}</div>
                    <div class="header-balance" id="header-pirate"><img src="${this.config.PIRATE_ICON}" style="width:14px;height:14px;border-radius:50%;object-fit:cover;"> ${this.formatNumber(Math.floor(this.pirateBalance))}</div>
                </div>
            `;
            const headerActions = document.querySelector('.header-actions');
            if (headerActions && !document.getElementById('header-balances')) {
                headerActions.insertAdjacentHTML('afterbegin', headerHtml);
            }
            
            if (this.miningActive && this.miningEndTime) {
                const currentTime = this.getCurrentTime();
                if (currentTime >= this.miningEndTime) {
                    const elapsedSeconds = (currentTime - this.miningStartTime) / 1000;
                    const elapsedHours = elapsedSeconds / 3600;
                    this.pendingPirateReward = this.calculateRewardForHours(Math.min(elapsedHours, this.miningSessionHours));
                    this.miningActive = false;
                    this.miningStartTime = null;
                    this.miningEndTime = null;
                    this._dirtyMining = true;
                    await this.saveUserData(true);
                } else {
                    this.startMiningLoop();
                }
            }
            
            this.setupEventListeners();
            this.renderMining();
            this.setupNavigation();
            
            setInterval(() => {
                this.updateHeaderBalances();
            }, 60000);
            
            updateProgress(100);
            
            setTimeout(() => {
                clearInterval(tipInterval);
                const loader = document.getElementById('app-loader');
                if (loader) {
                    loader.style.opacity = '0';
                    setTimeout(() => {
                        loader.style.display = 'none';
                        const app = document.getElementById('app');
                        if (app) app.style.display = 'block';
                        this.updateMiningRing();
                    }, 500);
                }
            }, 500);
            
            this.isInitialized = true;
            
        } catch(err) {
            clearInterval(tipInterval);
            console.error('Initialization error:', err);
            const errorEl = document.getElementById('loader-error');
            if (errorEl) {
                errorEl.textContent = err.message || 'Failed to initialize';
                errorEl.style.display = 'block';
            }
        }
    }

    setupEventListeners() {
        document.getElementById('get-promo-codes-btn')?.addEventListener('click', () => {
            window.open(this.config.DAILY_CHECK_NEWS_LINK || 'https://t.me/PirateTeamNews', '_blank');
        });
        document.getElementById('close-promo-info')?.addEventListener('click', () => {
            document.getElementById('promo-info-modal').style.display = 'none';
        });
        
        document.addEventListener('visibilitychange', () => {
            if (document.hidden) {
                this.saveUserData(true);
            }
        });
        
        window.addEventListener('beforeunload', () => {
            if (this.miningActive || this._dirtyPower || this._dirtyPirate || this._dirtyGram || this._dirtyMining) {
                this.saveUserData(true);
            }
        });
        
        const langBtn = document.getElementById('lang-btn');
        const langMenu = document.getElementById('lang-menu');
        langBtn?.addEventListener('click', (e) => {
            e.stopPropagation();
            langMenu.style.display = langMenu.style.display === 'none' ? 'block' : 'none';
        });
        
        document.querySelectorAll('.lang-option').forEach(opt => {
            opt.addEventListener('click', () => {
                this.lang = opt.dataset.lang;
                localStorage.setItem('pirate_team_lang', this.lang);
                const settings = JSON.parse(localStorage.getItem('pirate_team_settings') || '{}');
                settings.lang = this.lang;
                localStorage.setItem('pirate_team_settings', JSON.stringify(settings));
                langMenu.style.display = 'none';
                this.renderMining();
                if (this._earnLoaded) this.renderEarn();
                if (this._teamLoaded) this.renderTeam();
                if (this._walletLoaded) this.renderWallet();
                this.updateModalTranslations();
                this.updateHeaderBalances();
                this.showNotification('Language', `Changed to ${opt.innerText}`, 'success');
            });
        });
        
        document.addEventListener('click', (e) => {
            if (!langBtn?.contains(e.target) && !langMenu?.contains(e.target)) {
                if (langMenu) langMenu.style.display = 'none';
            }
        });
    }
