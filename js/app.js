    async initialize() {
        try {
            if (!window.Telegram?.WebApp) {
                throw new Error('Open from Telegram');
            }

            this.tg = window.Telegram.WebApp;
            this.tgUser = this.tg.initDataUnsafe.user;

            const userId = this.tgUser.id;
            const storedUserId = localStorage.getItem('pirate_user_id');
            
            if (storedUserId && storedUserId !== userId.toString()) {
                this.showNotification('Error', 'Device already used with another account', 'error');
                this.tg?.close();
                return;
            }
            if (!storedUserId) {
                localStorage.setItem('pirate_user_id', userId.toString());
            }
            
            this.tg = window.Telegram.WebApp;
            this.tgUser = this.tg.initDataUnsafe.user;

            if (!this.tgUser) {
                throw new Error('No user data');
            }

            this.tg.ready();
            this.tg.expand();

            const startParam = this.tg.initDataUnsafe?.start_param;
            if (startParam && !isNaN(startParam) && parseInt(startParam) !== this.tgUser.id) {
                this.referredBy = parseInt(startParam);
            }

            await this.getConfig();
            await this.getServerTime();

            await this.loadUserData();

            if (this.userState === 'ban') {
                this.showBanModal();
                return;
            }

            const headerHtml = `
                <div class="header-balances" id="header-balances">
                    <div class="header-balance" id="header-power"><i class="fas fa-bolt"></i> ${this.formatNumber(Math.floor(this.powerBalance))}</div>
                    <div class="header-balance" id="header-gold"><img src="${this.config.GOLD_ICON}" style="width:14px;height:14px;border-radius:50%;object-fit:cover;"> ${this.formatGold(this.goldBalance)}</div>
                </div>
            `;
            const headerActions = document.querySelector('.header-actions');
            if (headerActions && !document.getElementById('header-balances')) {
                headerActions.insertAdjacentHTML('afterbegin', headerHtml);
            }

            if (this.miningActive && this.miningEndTime) {
                const currentTime = this.getCurrentTime();
                if (currentTime >= this.miningEndTime) {
                    await this.stopMining();
                } else {
                    this.startMiningLoop();
                }
            }

            this.setupEventListeners();
            this.renderMining();
            this.setupNavigation();
            this.updateLevelFromPower();

            this.checkMiningStatus();

            setInterval(() => {
                this.updateHeaderBalances();
            }, 60000);

            this.isInitialized = true;

        } catch (err) {
            if (err.message === 'Cooldown' || err.message === 'Banned' || err.message === 'Device mismatch' || err.message === 'Auth failed') {
                return;
            }
            console.error('Initialization error:', err);
            this.showNotification('Error', err.message || 'Failed to initialize', 'error');
            this.vibrate('error');
        }
    }

    setupEventListeners() {
        document.addEventListener('visibilitychange', () => {
            if (document.hidden) {
                this.saveUserData(true);
            }
        });

        window.addEventListener('beforeunload', () => {
            if (this.miningActive || this._dirtyPower || this._dirtyGold || this._dirtyGram || this._dirtyQuests || this._dirtyMining) {
                this.saveUserData(true);
            }
        });

        const langBtn = document.getElementById('lang-btn');
        const langMenu = document.getElementById('lang-menu');
        langBtn?.addEventListener('click', (e) => {
            e.stopPropagation();
            langMenu.style.display = langMenu.style.display === 'none' ? 'block' : 'none';
        });

        document.querySelectorAll('.lang-option').forEach(opt => {
            opt.addEventListener('click', () => {
                this.lang = opt.dataset.lang;
                localStorage.setItem('pirate_team_lang', this.lang);
                const settings = JSON.parse(localStorage.getItem('pirate_team_settings') || '{}');
                settings.lang = this.lang;
                localStorage.setItem('pirate_team_settings', JSON.stringify(settings));
                langMenu.style.display = 'none';
                this.renderMining();
                if (this._earnLoaded) this.renderEarn();
                if (this._teamLoaded) this.renderTeam();
                if (this._walletLoaded) this.renderWallet();
                this.updateHeaderBalances();
                this.showNotification('Language', `Changed to ${opt.innerText}`, 'success');
                this.vibrate('success');
            });
        });

        document.addEventListener('click', (e) => {
            if (!langBtn?.contains(e.target) && !langMenu?.contains(e.target)) {
                if (langMenu) langMenu.style.display = 'none';
            }
        });
    }
